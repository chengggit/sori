use crate::dictionary::Definition;
use rusqlite::{Connection, OptionalExtension, Row, params};
use serde::{Deserialize, Serialize};

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SaveVocabulary {
    pub word: String,
    pub normalized_form: Option<String>,
    pub document_id: i64,
    pub context: String,
    pub definition: Option<Definition>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct VocabularyEntry {
    pub id: i64,
    pub word: String,
    pub normalized_form: Option<String>,
    pub document_id: Option<i64>,
    pub source_title: String,
    pub context: String,
    /// Unix time in seconds, generated by SQLite.
    pub created_at: i64,
    pub definition: Option<Definition>,
}

fn entry(row: &Row<'_>) -> rusqlite::Result<VocabularyEntry> {
    Ok(VocabularyEntry {
        id: row.get(0)?,
        word: row.get(1)?,
        normalized_form: row.get(2)?,
        document_id: row.get(3)?,
        source_title: row.get(4)?,
        context: row.get(5)?,
        created_at: row.get(6)?,
        definition: row
            .get::<_, Option<String>>(7)?
            .map(|json| {
                serde_json::from_str(&json).map_err(|error| {
                    rusqlite::Error::FromSqlConversionFailure(
                        7,
                        rusqlite::types::Type::Text,
                        Box::new(error),
                    )
                })
            })
            .transpose()?,
    })
}

pub fn save(database: &Connection, input: SaveVocabulary) -> Result<VocabularyEntry, String> {
    let word = input.word.trim();
    if word.is_empty() {
        return Err("Select a word to save.".into());
    }
    if input.context.trim().is_empty() {
        return Err("Include the original context for this word.".into());
    }
    let normalized_form = input.normalized_form.as_deref().map(str::trim);
    if normalized_form == Some("") {
        return Err("The normalized form must contain text when provided.".into());
    }

    if let Some(definition) = &input.definition
        && (definition.text.trim().is_empty()
            || definition.text.len() > 32_768
            || definition.term.trim().is_empty()
            || definition.term.chars().count() > 100
            || definition.source_url != crate::dictionary::source_url(&definition.term))
    {
        return Err("Invalid dictionary definition.".into());
    }
    let transaction = database
        .unchecked_transaction()
        .map_err(|error| error.to_string())?;
    // A transaction keeps the definition snapshot and source selection consistent.
    // Preserve the first saved form and timestamp when the same selection is saved again.
    let id: i64 = transaction
        .query_row(
            "INSERT INTO vocabulary (word, normalized_form, document_id, source_title, context)
         SELECT ?1, ?2, id, title, ?3 FROM documents WHERE id = ?4
         ON CONFLICT (document_id, word, context) DO UPDATE SET word = excluded.word
         RETURNING id",
            params![word, normalized_form, input.context, input.document_id],
            |row| row.get(0),
        )
        .optional()
        .map_err(|error| error.to_string())?
        .ok_or_else(|| "Source document not found.".to_string())?;
    if let Some(definition) = input.definition {
        transaction.execute(
            "INSERT OR IGNORE INTO vocabulary_meanings (vocabulary_id, definition_json) VALUES (?1, ?2)",
            params![id, serde_json::to_string(&definition).map_err(|error| error.to_string())?],
        ).map_err(|error| error.to_string())?;
    }
    let saved = transaction.query_row(
        "SELECT v.id, word, normalized_form, document_id, source_title, context, created_at, definition_json
         FROM vocabulary v LEFT JOIN vocabulary_meanings m ON m.vocabulary_id = v.id WHERE v.id = ?1",
        [id], entry,
    ).map_err(|error| error.to_string())?;
    transaction.commit().map_err(|error| error.to_string())?;
    Ok(saved)
}

pub fn list(database: &Connection) -> Result<Vec<VocabularyEntry>, String> {
    let mut statement = database
        .prepare(
            "SELECT v.id, word, normalized_form, document_id, source_title, context, created_at, definition_json
         FROM vocabulary v LEFT JOIN vocabulary_meanings m ON m.vocabulary_id = v.id ORDER BY created_at DESC, v.id DESC",
        )
        .map_err(|error| error.to_string())?;
    statement
        .query_map([], entry)
        .map_err(|error| error.to_string())?
        .collect::<Result<Vec<_>, _>>()
        .map_err(|error| error.to_string())
}

pub fn remove(database: &Connection, id: i64) -> Result<(), String> {
    database
        .execute("DELETE FROM vocabulary WHERE id = ?1", [id])
        .map_err(|error| error.to_string())?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn database() -> Connection {
        let database = Connection::open_in_memory().unwrap();
        database.pragma_update(None, "foreign_keys", true).unwrap();
        database.execute_batch(include_str!("schema.sql")).unwrap();
        database.execute(
            "INSERT INTO documents (id, title, content) VALUES (1, '이야기', '학교에 갔어요. 학교가 커요.')", []
        ).unwrap();
        database
    }

    fn selection() -> SaveVocabulary {
        SaveVocabulary {
            word: "갔어요".into(),
            normalized_form: Some("가다".into()),
            document_id: 1,
            context: "학교에 갔어요.".into(),
            definition: None,
        }
    }

    #[test]
    fn saves_selection_with_original_context_and_source_snapshot() {
        let database = database();
        let mut input = selection();
        input.word = "  갔어요  ".into();
        input.context = "  학교에 갔어요.\n".into();
        let saved = save(&database, input).unwrap();
        assert_eq!(saved.word, "갔어요");
        assert_eq!(saved.normalized_form.as_deref(), Some("가다"));
        assert_eq!(saved.document_id, Some(1));
        assert_eq!(saved.source_title, "이야기");
        assert_eq!(saved.context, "  학교에 갔어요.\n");
        assert!(saved.created_at > 0);
        let listed = list(&database).unwrap();
        assert_eq!(listed.len(), 1);
        assert_eq!(listed[0].id, saved.id);
    }

    #[test]
    fn repeated_saves_preserve_the_original_entry() {
        let database = database();
        let saved = save(&database, selection()).unwrap();
        let mut repeated = selection();
        repeated.normalized_form = None;
        let duplicate = save(&database, repeated).unwrap();
        assert_eq!(duplicate.id, saved.id);
        assert_eq!(duplicate.created_at, saved.created_at);
        assert_eq!(duplicate.normalized_form, saved.normalized_form);
        assert_eq!(list(&database).unwrap().len(), 1);
    }

    #[test]
    fn definition_snapshots_survive_offline_reads_and_source_deletion() {
        let database = database();
        let mut input = selection();
        let definition = Definition {
            term: "가다".into(),
            part_of_speech: "Verb".into(),
            text: "to go".into(),
            source_url: crate::dictionary::source_url("가다"),
        };
        input.definition = Some(definition.clone());
        let saved = save(&database, input).unwrap();
        assert_eq!(saved.definition, Some(definition.clone()));
        assert_eq!(
            save(&database, selection()).unwrap().definition,
            Some(definition.clone())
        );
        database.execute("DELETE FROM documents", []).unwrap();
        assert_eq!(list(&database).unwrap()[0].definition, Some(definition));
        remove(&database, saved.id).unwrap();
        let remaining: i64 = database
            .query_row("SELECT count(*) FROM vocabulary_meanings", [], |row| {
                row.get(0)
            })
            .unwrap();
        assert_eq!(remaining, 0);
    }

    #[test]
    fn retains_different_contexts_and_sources_in_newest_first_order() {
        let database = database();
        let first = save(&database, selection()).unwrap();
        let mut another_context = selection();
        another_context.context = "어제 학교에 갔어요.".into();
        let second = save(&database, another_context).unwrap();
        database
            .execute(
                "INSERT INTO documents VALUES (2, '다른 책', '학교에 갔어요.')",
                [],
            )
            .unwrap();
        let mut another_source = selection();
        another_source.document_id = 2;
        another_source.normalized_form = None;
        let third = save(&database, another_source).unwrap();
        assert!(third.normalized_form.is_none());
        let ids: Vec<_> = list(&database)
            .unwrap()
            .iter()
            .map(|item| item.id)
            .collect();
        assert_eq!(ids, [third.id, second.id, first.id]);
    }

    #[test]
    fn invalid_saves_leave_collection_empty() {
        let database = database();
        let mut input = selection();
        input.word = " \n".into();
        assert!(save(&database, input).is_err());
        let mut input = selection();
        input.context = " \n".into();
        assert!(save(&database, input).is_err());
        let mut input = selection();
        input.normalized_form = Some(" \n".into());
        assert!(save(&database, input).is_err());
        let mut input = selection();
        input.document_id = 999;
        assert_eq!(
            save(&database, input).unwrap_err(),
            "Source document not found."
        );
        assert!(list(&database).unwrap().is_empty());
    }

    #[test]
    fn source_deletion_preserves_saved_words_and_removal_is_idempotent() {
        let database = database();
        let saved = save(&database, selection()).unwrap();
        database
            .execute("DELETE FROM documents WHERE id = 1", [])
            .unwrap();
        let listed = list(&database).unwrap();
        assert_eq!(listed.len(), 1);
        assert_eq!(listed[0].document_id, None);
        assert_eq!(listed[0].source_title, "이야기");
        assert_eq!(listed[0].context, "학교에 갔어요.");
        remove(&database, saved.id).unwrap();
        remove(&database, saved.id).unwrap();
        assert!(list(&database).unwrap().is_empty());
    }
}
