use crate::dictionary::Definition;
use rusqlite::{params, Connection, OptionalExtension, Row, TransactionBehavior};
use serde::{Deserialize, Serialize};

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SaveVocabulary {
    pub word: String,
    pub normalized_form: Option<String>,
    pub document_id: i64,
    pub context: String,
    pub definition: Option<Definition>,
    #[serde(default)]
    pub tags: Vec<String>,
}

#[derive(Debug, Deserialize)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum VideoSource {
    Local { id: i64 },
    Youtube { id: String, title: String },
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SaveVideoVocabulary {
    pub source: VideoSource,
    pub word: String,
    pub normalized_form: Option<String>,
    pub context: String,
    pub definition: Option<Definition>,
    pub tags: Vec<String>,
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct EditVocabulary {
    pub normalized_form: String,
    pub meaning: String,
    pub note: String,
    pub tags: Vec<String>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct VocabularyEntry {
    pub id: i64,
    pub word: String,
    pub normalized_form: Option<String>,
    pub document_id: Option<i64>,
    pub source_title: String,
    pub context: String,
    /// Unix time in seconds, generated by SQLite.
    pub created_at: i64,
    pub definition: Option<Definition>,
    pub tags: Vec<String>,
}

fn entry(row: &Row<'_>) -> rusqlite::Result<VocabularyEntry> {
    Ok(VocabularyEntry {
        id: row.get(0)?,
        word: row.get(1)?,
        normalized_form: row.get(2)?,
        document_id: row.get(3)?,
        source_title: row.get(4)?,
        context: row.get(5)?,
        created_at: row.get(6)?,
        tags: serde_json::from_str(&row.get::<_, String>(8)?).map_err(|error| {
            rusqlite::Error::FromSqlConversionFailure(
                8,
                rusqlite::types::Type::Text,
                Box::new(error),
            )
        })?,
        definition: row
            .get::<_, Option<String>>(7)?
            .map(|json| {
                serde_json::from_str(&json).map_err(|error| {
                    rusqlite::Error::FromSqlConversionFailure(
                        7,
                        rusqlite::types::Type::Text,
                        Box::new(error),
                    )
                })
            })
            .transpose()?,
    })
}

pub fn save(database: &Connection, input: SaveVocabulary) -> Result<VocabularyEntry, String> {
    let word = input.word.trim();
    if word.is_empty() {
        return Err("Select a word to save.".into());
    }
    if input.context.trim().is_empty() {
        return Err("Include the original context for this word.".into());
    }
    let normalized_form = input.normalized_form.as_deref().map(str::trim);
    if normalized_form == Some("") {
        return Err("The normalized form must contain text when provided.".into());
    }
    validate_tags(&input.tags)?;
    validate_definition(input.definition.as_ref())?;
    let transaction = database
        .unchecked_transaction()
        .map_err(|error| error.to_string())?;
    // A transaction keeps the definition snapshot and source selection consistent.
    // Preserve the first saved form and timestamp when the same selection is saved again.
    let id: i64 = transaction
        .query_row(
            "INSERT INTO vocabulary (word, normalized_form, document_id, source_title, context)
         SELECT ?1, ?2, id, title, ?3 FROM documents WHERE id = ?4
         ON CONFLICT (document_id, word, context) DO UPDATE SET word = excluded.word
         RETURNING id",
            params![word, normalized_form, input.context, input.document_id],
            |row| row.get(0),
        )
        .optional()
        .map_err(|error| error.to_string())?
        .ok_or_else(|| "Source document not found.".to_string())?;
    if let Some(definition) = input.definition {
        transaction.execute(
            "INSERT OR IGNORE INTO vocabulary_meanings (vocabulary_id, definition_json) VALUES (?1, ?2)",
            params![id, serde_json::to_string(&definition).map_err(|error| error.to_string())?],
        ).map_err(|error| error.to_string())?;
    }
    insert_tags(&transaction, id, &input.tags)?;
    let saved = read_entry(&transaction, id)?;
    transaction.commit().map_err(|error| error.to_string())?;
    Ok(saved)
}

pub fn save_video(
    database: &Connection,
    input: SaveVideoVocabulary,
) -> Result<VocabularyEntry, String> {
    let word = input.word.trim();
    let context = input.context.trim();
    if word.is_empty() || context.is_empty() || context.len() > 16_384 {
        return Err("Enter a word and select a subtitle cue up to 16 KiB.".into());
    }
    validate_tags(&input.tags)?;
    validate_definition(input.definition.as_ref())?;
    let normalized_form = input
        .normalized_form
        .as_deref()
        .map(str::trim)
        .filter(|form| !form.is_empty() && *form != word);
    let transaction =
        rusqlite::Transaction::new_unchecked(database, TransactionBehavior::Immediate)
            .map_err(|error| error.to_string())?;
    let (video_id, youtube_id, title) = match input.source {
        VideoSource::Local { id } => {
            let title: String = transaction
                .query_row("SELECT title FROM videos WHERE id = ?1", [id], |row| {
                    row.get(0)
                })
                .optional()
                .map_err(|error| error.to_string())?
                .ok_or("Video not found.")?;
            (Some(id), None, title)
        }
        VideoSource::Youtube { id, title } => {
            if id.len() != 11
                || !id
                    .bytes()
                    .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_'))
            {
                return Err("Invalid YouTube video ID.".into());
            }
            (None, Some(id), title.trim().chars().take(500).collect())
        }
    };
    let existing =
        find_video_entry_id(&transaction, video_id, youtube_id.as_deref(), word, context)?;
    let id = if let Some(id) = existing {
        id
    } else {
        let id = transaction
            .query_row(
                "INSERT INTO vocabulary (word, normalized_form, source_title, context)
             VALUES (?1, ?2, ?3, ?4) RETURNING id",
                params![word, normalized_form, title, context],
                |row| row.get::<_, i64>(0),
            )
            .map_err(|error| error.to_string())?;
        transaction.execute(
            "INSERT INTO video_vocabulary (vocabulary_id, video_id, youtube_id) VALUES (?1, ?2, ?3)",
            params![id, video_id, youtube_id],
        ).map_err(|error| error.to_string())?;
        if let Some(definition) = input.definition {
            transaction
            .execute(
                "INSERT INTO vocabulary_meanings (vocabulary_id, definition_json) VALUES (?1, ?2)",
                params![
                    id,
                    serde_json::to_string(&definition).map_err(|error| error.to_string())?
                ],
            )
            .map_err(|error| error.to_string())?;
        }
        insert_tags(&transaction, id, &input.tags)?;
        id
    };
    let saved = read_entry(&transaction, id)?;
    transaction.commit().map_err(|error| error.to_string())?;
    Ok(saved)
}

pub fn find_video_entry(
    database: &Connection,
    source: VideoSource,
    word: &str,
    context: &str,
) -> Result<Option<VocabularyEntry>, String> {
    let (video_id, youtube_id) = match &source {
        VideoSource::Local { id } => (Some(*id), None),
        VideoSource::Youtube { id, .. } => (None, Some(id.as_str())),
    };
    find_video_entry_id(database, video_id, youtube_id, word.trim(), context.trim())?
        .map(|id| read_entry(database, id))
        .transpose()
}

fn find_video_entry_id(
    database: &Connection,
    video_id: Option<i64>,
    youtube_id: Option<&str>,
    word: &str,
    context: &str,
) -> Result<Option<i64>, String> {
    database
        .query_row(
            "SELECT v.id FROM vocabulary v JOIN video_vocabulary link ON link.vocabulary_id = v.id
         WHERE link.video_id IS ?1 AND link.youtube_id IS ?2 AND v.word = ?3 AND v.context = ?4",
            params![video_id, youtube_id, word, context],
            |row| row.get(0),
        )
        .optional()
        .map_err(|error| error.to_string())
}

pub fn edit(
    database: &Connection,
    id: i64,
    input: EditVocabulary,
) -> Result<VocabularyEntry, String> {
    validate_tags(&input.tags)?;
    let meaning = input.meaning.trim();
    let note = input.note.trim();
    if meaning.is_empty() && !note.is_empty() {
        return Err("Enter a meaning to save a note.".into());
    }

    let transaction =
        rusqlite::Transaction::new_unchecked(database, TransactionBehavior::Immediate)
            .map_err(|error| error.to_string())?;
    let current = read_entry(&transaction, id)?;
    let normalized = input.normalized_form.trim();
    let normalized_form =
        (!normalized.is_empty() && normalized != current.word).then_some(normalized);
    let definition = if meaning.is_empty() {
        None
    } else {
        let mut definition = current.definition.unwrap_or_else(|| Definition {
            term: normalized_form.unwrap_or(&current.word).to_string(),
            part_of_speech: String::new(),
            text: String::new(),
            source_url: String::new(),
            hanja: None,
            custom: true,
            note: None,
        });
        definition.custom |= definition.text != meaning;
        definition.text = meaning.to_string();
        definition.note = (!note.is_empty()).then(|| note.to_string());
        Some(definition)
    };
    validate_definition(definition.as_ref())?;

    transaction
        .execute(
            "UPDATE vocabulary SET normalized_form = ?1 WHERE id = ?2",
            params![normalized_form, id],
        )
        .map_err(|error| error.to_string())?;
    if let Some(definition) = definition {
        transaction
            .execute(
                "INSERT INTO vocabulary_meanings (vocabulary_id, definition_json) VALUES (?1, ?2)
             ON CONFLICT (vocabulary_id) DO UPDATE SET definition_json = excluded.definition_json",
                params![
                    id,
                    serde_json::to_string(&definition).map_err(|error| error.to_string())?
                ],
            )
            .map_err(|error| error.to_string())?;
    } else {
        transaction
            .execute(
                "DELETE FROM vocabulary_meanings WHERE vocabulary_id = ?1",
                [id],
            )
            .map_err(|error| error.to_string())?;
    }
    transaction
        .execute("DELETE FROM vocabulary_tags WHERE vocabulary_id = ?1", [id])
        .map_err(|error| error.to_string())?;
    insert_tags(&transaction, id, &input.tags)?;
    let updated = read_entry(&transaction, id)?;
    transaction.commit().map_err(|error| error.to_string())?;
    Ok(updated)
}

fn validate_tags(tags: &[String]) -> Result<(), String> {
    if tags.len() > 20
        || tags.iter().any(|tag| {
            tag.trim().is_empty() || tag.chars().count() > 50 || tag.chars().any(char::is_control)
        })
    {
        return Err("Use up to 20 tags, each containing 1–50 characters.".into());
    }
    Ok(())
}

fn validate_definition(definition: Option<&Definition>) -> Result<(), String> {
    let Some(definition) = definition else {
        return Ok(());
    };
    if definition.text.trim().is_empty()
        || definition.text.len() > 32_768
        || definition.term.trim().is_empty()
        || definition.term.chars().count() > 100
        || (definition.source_url != crate::dictionary::source_url(&definition.term)
            && !(definition.custom && definition.source_url.is_empty()))
        || definition
            .note
            .as_ref()
            .is_some_and(|note| note.len() > 16_000)
    {
        return Err("Invalid saved meaning.".into());
    }
    Ok(())
}

fn insert_tags(database: &Connection, id: i64, tags: &[String]) -> Result<(), String> {
    for tag in tags {
        database
            .execute(
                "INSERT OR IGNORE INTO vocabulary_tags (vocabulary_id, tag) VALUES (?1, ?2)",
                params![id, tag.trim()],
            )
            .map_err(|error| error.to_string())?;
    }
    Ok(())
}

fn read_entry(database: &Connection, id: i64) -> Result<VocabularyEntry, String> {
    database.query_row(
        "SELECT v.id, word, normalized_form, document_id, source_title, context, created_at, definition_json,
         (SELECT json_group_array(tag) FROM vocabulary_tags WHERE vocabulary_id = v.id)
         FROM vocabulary v LEFT JOIN vocabulary_meanings m ON m.vocabulary_id = v.id WHERE v.id = ?1",
        [id], entry,
    ).optional().map_err(|error| error.to_string())?
        .ok_or_else(|| "Saved word not found.".into())
}

pub fn list(database: &Connection) -> Result<Vec<VocabularyEntry>, String> {
    let mut statement = database
        .prepare(
            "SELECT v.id, word, normalized_form, document_id, source_title, context, created_at, definition_json,
         (SELECT json_group_array(tag) FROM vocabulary_tags WHERE vocabulary_id = v.id)
         FROM vocabulary v LEFT JOIN vocabulary_meanings m ON m.vocabulary_id = v.id ORDER BY created_at DESC, v.id DESC",
        )
        .map_err(|error| error.to_string())?;
    let rows = statement
        .query_map([], entry)
        .map_err(|error| error.to_string())?;
    rows.collect::<Result<Vec<_>, _>>()
        .map_err(|error| error.to_string())
}

pub fn remove(database: &Connection, id: i64) -> Result<(), String> {
    database
        .execute("DELETE FROM vocabulary WHERE id = ?1", [id])
        .map_err(|error| error.to_string())?;
    Ok(())
}

